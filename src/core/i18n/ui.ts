export const UI: Record<Lang, Record<UiKey, string>> = { en, pl, de, fr };

export function isUiKey(key: string): key is UiKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}

/**
 * Looks `key` up in `lang`, falls back to English, then to the key itself (so a typo is visible,
 * never an empty label). Fills {name} placeholders from `params`; an unknown placeholder stays as is.
 */
export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  const table: Record<string, string> = UI[lang] ?? UI.en;
  const template = table[key] ?? (UI.en as Record<string, string>)[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole,
  );
}

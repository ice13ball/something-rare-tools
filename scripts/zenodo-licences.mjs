// Regenerates src/core/metadata/zenodo-licences.ts from Zenodo's published licence vocabulary
// (https://zenodo.org/api/vocabularies/licenses). Run by hand when Zenodo changes its list; NEVER at build or test time:
//   node scripts/zenodo-licences.mjs
// Keeps only the ids the classifier already knows (src/core/metadata/spdx-data.ts), so the table can never add a licence to the tool.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const site = readFileSync(new URL('config/site.ts', root), 'utf8');
const origin = /origin:\s*'([^']+)'/.exec(site)?.[1];
const email = /contactEmail:\s*'([^']+)'/.exec(site)?.[1];
if (!origin || !email) throw new Error('config/site.ts: origin / contactEmail not found');
// The same User-Agent the server's fetch proxy sends (server/fetchProxy.ts USER_AGENT).
const USER_AGENT = `AbyssalClaimsTools/1.0 (+${origin}; mailto:${email})`;

const known = [...readFileSync(new URL('src/core/metadata/spdx-data.ts', root), 'utf8').matchAll(/\{ id: "([^"]+)"/g)].map((m) => m[1]);
const byLower = new Map(known.map((id) => [id.toLowerCase(), id]));

const hits = [];
for (let url = 'https://zenodo.org/api/vocabularies/licenses?size=100&page=1'; url; ) {
  const res = await fetch(url, { headers: { 'User-Agent': USER_AGENT, Accept: 'application/json' } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const json = await res.json();
  hits.push(...json.hits.hits);
  url = json.links?.next;
  if (hits.length > json.hits.total + 1000) throw new Error('paging does not end');
}

const rows = [];
for (const h of hits) {
  const id = byLower.get(String(h.id).toLowerCase());
  if (!id) continue;
  const title = h.title?.en;
  const url = h.props?.url;
  if (!title || !url || h.props?.scheme !== 'spdx') continue;
  rows.push({ id, title, url });
}
rows.sort((a, b) => (a.id < b.id ? -1 : 1));

const date = new Date().toISOString().slice(0, 10);
const out = `// SPDX-License-Identifier: AGPL-3.0-or-later
// Based on Abyssal Claims — © 2026 Michal Mazurowski — https://something-rare.com
// GENERATED by scripts/zenodo-licences.mjs from https://zenodo.org/api/vocabularies/licenses, fetched ${date} (${hits.length} entries in the vocabulary).
// Only the ${rows.length} entries whose id the classifier already knows (spdx-data.ts); id is the canonical SPDX case, title and url are Zenodo's own.
// Zenodo writes a DataCite rights entry from exactly these: rights = title, rightsUri = url, rightsIdentifier = id (lower case), scheme SPDX.
// Regenerate by hand when Zenodo changes the list; do not edit; never fetched at build or test time.

export const ZENODO_LICENCES_FETCHED = ${JSON.stringify(date)};

export const ZENODO_LICENCES: readonly { id: string; title: string; url: string }[] = [
${rows.map((r) => `  { id: ${JSON.stringify(r.id)}, title: ${JSON.stringify(r.title)}, url: ${JSON.stringify(r.url)} },`).join('\n')}
];
`;
writeFileSync(fileURLToPath(new URL('src/core/metadata/zenodo-licences.ts', root)), out);
console.log(`${rows.length} of ${hits.length} entries written`);
